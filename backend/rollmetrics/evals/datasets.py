def ensure_eval_datasets(knowledge_dir: Path, overwrite: bool = False) -> dict[str, Path]:
    """Ensures knowledge_base/evals/*.json exist on disk and returns their paths."""
    evals_dir = knowledge_dir / "evals"
    evals_dir.mkdir(parents=True, exist_ok=True)

    paths = {
        "ibjjf_rule_cases": evals_dir / "ibjjf_rule_cases.json",
        "match_timelines": evals_dir / "match_timelines.json",
        "cta_coaching_queries": evals_dir / "cta_coaching_queries.json",
    }

    if overwrite or not paths["ibjjf_rule_cases"].exists():
        paths["ibjjf_rule_cases"].write_text(
            json.dumps({"version": "v0.1.0", "cases": default_ibjjf_rule_cases()}, indent=2) + "\n",
            encoding="utf-8",
        )
    if overwrite or not paths["match_timelines"].exists():
        paths["match_timelines"].write_text(
            json.dumps({"version": "v0.1.0", "timelines": default_match_timelines()}, indent=2) + "\n",
            encoding="utf-8",
        )
    if overwrite or not paths["cta_coaching_queries"].exists():
        paths["cta_coaching_queries"].write_text(
            json.dumps({"version": "v0.1.0", "queries": default_cta_coaching_queries()}, indent=2) + "\n",
            encoding="utf-8",
        )
    return paths
